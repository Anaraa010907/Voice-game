export interface RuleMode {
  /** Оноогоор тоглох эсэх (Энгийн ангилал үргэлж true) */
  points: boolean;
  /** Энгийн ангилал: "шийтгэлийн оноо" гэж нэрлэнэ */
  simple: boolean;
}

/** {ууна} / {уух} орлуулагчийг горимд тохируулан хөрвүүлнэ */
export function fill(text: string, mode: RuleMode): string {
  const ууна = mode.simple ? "1 шийтгэлийн оноо авна" : mode.points ? "1 оноо авна" : "1 балгам ууна";
  const уух = mode.simple ? "шийтгэлийн оноо авах" : mode.points ? "оноо авах" : "балгам уух";
  return text.replace(/\{ууна\}/g, ууна).replace(/\{уух\}/g, уух);
}

