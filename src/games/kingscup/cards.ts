export interface CardOption {
  /** Товчны нэр: "ҮНЭН", "ЗОРИГ" */
  label: string;
  text: string;
}

export interface CardDef {
  id: string;
  kind: KindId;
  title: string;
  /** Үндсэн даалгавар эсвэл асуулт */
  text?: string;
  /** Тоглогч аль нэгийг нь сонгох хувилбарууд (Үнэн эсвэл зориг) */
  options?: CardOption[];
  /** "Санамсаргүй хүн" товч гаргах эсэх (нэр оруулсан үед) */
  pickPerson?: boolean;
  /** Зөвхөн эдгээр ангилалд орно. Байхгүй бол үндсэн багцад орно. */
  categories?: CategoryId[];
}

