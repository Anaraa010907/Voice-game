/** Тухайн ангилалд тоглох картууд: үндсэн картууд + (байвал) ангиллын тусгай картууд */
export function cardsFor(categoryId: CategoryId | null): CardDef[] {
  return CARDS.filter((c) => !c.categories || (categoryId !== null && c.categories.includes(categoryId)));
}

/** Тусгай картуудтай ангиллууд. Байхгүй бол тохиргоонд ангилал сонгуулахгүй. */
export function categoriesWithCards(): Category[] {
  return CATEGORIES.filter((cat) => CARDS.some((c) => c.categories?.includes(cat.id)));
}

export function shuffle<T>(list: T[]): T[] {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
